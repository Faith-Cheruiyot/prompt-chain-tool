import type { Step, Output } from "./types";
import { resolvePrompt, checkReferences } from "./validation";

export type Generation = {
  text: string;
  images: { data: Uint8Array; mediaType: string }[];
};
export async function executeChain(options: {
  steps: Step[];
  input: string;
  image: Uint8Array | null;
  generate: (
    step: Step,
    prompt: string,
    system: string,
    image: Uint8Array | null,
  ) => Promise<Generation>;
  saveImage: (
    step: Step,
    image: Generation["images"][number],
    index: number,
  ) => Promise<string>;
  onOutput: (output: Output) => Promise<void>;
  onStep?: (position: number) => void;
  modelName: (step: Step) => string;
}) {
  const steps = [...options.steps].sort((a, b) => a.position - b.position);
  checkReferences(steps);
  const texts: string[] = [];
  let image = options.image;
  for (let i = 0; i < steps.length; i++) {
    const step = steps[i];
    options.onStep?.(i + 1);
    const start = Date.now();
    const previous = i === 0 ? options.input : texts[i - 1];
    const prompt = resolvePrompt(
      step.user_prompt,
      options.input,
      previous,
      texts,
      i + 1,
    );
    const system = resolvePrompt(
      step.system_prompt || "",
      options.input,
      previous,
      texts,
      i + 1,
    );
    // Previous output is always passed, even when the author omits a variable.
    const result = await options.generate(
      step,
      `${prompt}\n\n<step_input>\n${previous}\n</step_input>`,
      system,
      image,
    );
    if (step.output_type === "image" && !result.images.length)
      throw new Error(
        "The model did not return an image. Try a more specific image prompt.",
      );
    if (!result.text.trim() && !result.images.length)
      throw new Error("The model returned an empty response.");
    const media: Output["media"] = [];
    for (let n = 0; n < result.images.length; n++) {
      const file = result.images[n];
      const path = await options.saveImage(step, file, n);
      media.push({ path, media_type: file.mediaType });
    }
    if (result.images.length) image = result.images[0].data;
    const text = result.text || "[Image generated by the previous step.]";
    texts.push(text);
    await options.onOutput({
      step_id: step.id,
      name: step.name,
      position: i + 1,
      text: result.text,
      media,
      model: options.modelName(step),
      duration_ms: Date.now() - start,
    });
  }
}
